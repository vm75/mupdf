struct test_state
{
	int fail_after;
	int failing;
	int unhandled;
};

static void *
test_malloc(void *opaque, size_t size)
{
	struct test_state *state = opaque;
	if (state->fail_after > 0 && --state->fail_after == 0)
		state->failing = 1;
	return state->failing ? NULL : malloc(size);
}

static void *
test_realloc(void *opaque, void *ptr, size_t size)
{
	struct test_state *state = opaque;
	if (state->fail_after > 0 && --state->fail_after == 0)
		state->failing = 1;
	return state->failing ? NULL : realloc(ptr, size);
}

static void
test_free(void *opaque, void *ptr)
{
	(void)opaque;
	free(ptr);
}

static void
test_message(void *opaque, const char *message)
{
	struct test_state *state = opaque;
	if (strstr(message, "UNHANDLED EXCEPTION"))
		state->unhandled = 1;
}

