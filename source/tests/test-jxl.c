static void
check_sample(fz_context *ctx, const unsigned char *data, size_t size, const unsigned char *expected,
	int width, int height, int n, int alpha, int orientation, int tolerance)
{
	fz_buffer *buffer = NULL;
	fz_image *image = NULL;
	fz_pixmap *pixmap = NULL;
	fz_var(buffer);
	fz_var(image);
	fz_var(pixmap);
	fz_try(ctx)
	{
		int x, y, k;
		buffer = fz_new_buffer_from_copied_data(ctx, data, size);
		image = fz_new_image_from_buffer(ctx, buffer);
		CHECK(ctx, image->w == width && image->h == height);
		CHECK(ctx, image->xres == 72 && image->yres == 72);
		CHECK(ctx, fz_image_orientation(ctx, image) == orientation);
		pixmap = fz_get_unscaled_pixmap_from_image(ctx, image);
		CHECK(ctx, pixmap->w == width && pixmap->h == height);
		CHECK(ctx, pixmap->n == n && pixmap->alpha == alpha);
		CHECK(ctx, fz_colorspace_n(ctx, pixmap->colorspace) == n - alpha);
		CHECK(ctx, fz_colorspace_type(ctx, pixmap->colorspace) == (n - alpha == 1 ? FZ_COLORSPACE_GRAY : FZ_COLORSPACE_RGB));
#if FZ_ENABLE_ICC
		CHECK(ctx, fz_colorspace_is_icc(ctx, pixmap->colorspace));
#endif
		for (y = 0; y < height; ++y)
			for (x = 0; x < width; ++x)
				for (k = 0; k < n; ++k)
					CHECK(ctx, abs(pixmap->samples[y * pixmap->stride + x * n + k] - expected[(y * width + x) * n + k]) <= tolerance);
	}
	fz_always(ctx)
	{
		fz_drop_pixmap(ctx, pixmap);
		fz_drop_image(ctx, image);
		fz_drop_buffer(ctx, buffer);
	}
	fz_catch(ctx)
		fz_rethrow(ctx);
}

static void
check_allocation_failures(fz_context *ctx, struct test_state *state)
{
	fz_buffer *buffer = fz_new_buffer_from_copied_data(ctx, jxl_rgba, sizeof(jxl_rgba));
	fz_try(ctx)
	{
		int i;
		for (i = 1; i <= 40; ++i)
		{
			fz_image *image = NULL;
			fz_pixmap *pixmap = NULL;
			int caught = 0;
			fz_var(image);
			fz_var(pixmap);
			fz_var(caught);
			state->fail_after = i;
			fz_try(ctx)
			{
				image = fz_new_image_from_buffer(ctx, buffer);
				pixmap = fz_get_unscaled_pixmap_from_image(ctx, image);
			}
			fz_always(ctx)
			{
				state->failing = state->fail_after = 0;
				fz_drop_pixmap(ctx, pixmap);
				fz_drop_image(ctx, image);
			}
			fz_catch(ctx)
			{
				caught = fz_caught(ctx);
				fz_report_error(ctx);
			}
			CHECK(ctx, caught == FZ_ERROR_SYSTEM);
		}
	}
	fz_always(ctx)
		fz_drop_buffer(ctx, buffer);
	fz_catch(ctx)
		fz_rethrow(ctx);
	check_sample(ctx, jxl_rgb, sizeof(jxl_rgb), rgb, 2, 2, 3, 0, 1, 0);
}
