static void
check_error(fz_context *ctx, const unsigned char *data, size_t size, int expected)
{
	fz_buffer *buffer = fz_new_buffer_from_copied_data(ctx, data, size);
	fz_image *image = NULL;
	fz_pixmap *pixmap = NULL;
	int caught = 0;
	fz_var(image);
	fz_var(pixmap);
	fz_var(caught);
	fz_try(ctx)
	{
		image = fz_new_image_from_buffer(ctx, buffer);
		pixmap = fz_get_unscaled_pixmap_from_image(ctx, image);
	}
	fz_always(ctx)
	{
		fz_drop_pixmap(ctx, pixmap);
		fz_drop_image(ctx, image);
		fz_drop_buffer(ctx, buffer);
	}
	fz_catch(ctx)
	{
		caught = fz_caught(ctx);
		fz_report_error(ctx);
	}
	CHECK(ctx, caught == expected);
}

int
main(void)
{
	struct test_state state = { 0 };
	fz_alloc_context alloc = { &state, test_malloc, test_realloc, test_free };
	fz_context *ctx = fz_new_context(&alloc, NULL, FZ_STORE_DEFAULT);
	int failed = 0;
	fz_var(state);
	fz_var(failed);
	if (!ctx)
		return 1;
	fz_set_error_callback(ctx, test_message, &state);
	fz_set_warning_callback(ctx, test_message, &state);
	fz_try(ctx)
	{
		CHECK(ctx, fz_lookup_image_type("jxl") == FZ_IMAGE_JXL);
		CHECK(ctx, !strcmp(fz_image_type_name(FZ_IMAGE_JXL), "jxl"));
#if FZ_ENABLE_JXL
		check_sample(ctx, jxl_rgb, sizeof(jxl_rgb), rgb, 2, 2, 3, 0, 1, 0);
		check_sample(ctx, jxl_rgba, sizeof(jxl_rgba), rgba, 2, 2, 4, 1, 1, 0);
		check_sample(ctx, jxl_gray16, sizeof(jxl_gray16), gray, 2, 2, 1, 0, 1, 1);
		check_sample(ctx, jxl_gray_alpha, sizeof(jxl_gray_alpha), gray_alpha, 2, 2, 2, 1, 1, 1);
		check_sample(ctx, jxl_oriented, sizeof(jxl_oriented), oriented, 3, 2, 3, 0, 4, 0);
		check_sample(ctx, jxl_lossy, sizeof(jxl_lossy), lossy, 2, 2, 3, 0, 1, 5);
		check_sample(ctx, jxl_animated, sizeof(jxl_animated), rgb, 2, 2, 3, 0, 1, 0);
		check_error(ctx, jxl_rgb, 8, FZ_ERROR_FORMAT);
		check_error(ctx, jxl_rgba, 12, FZ_ERROR_FORMAT);
		check_allocation_failures(ctx, &state);
#else
		check_error(ctx, jxl_rgb, sizeof(jxl_rgb), FZ_ERROR_UNSUPPORTED);
		check_error(ctx, jxl_rgba, sizeof(jxl_rgba), FZ_ERROR_UNSUPPORTED);
#endif
		CHECK(ctx, !state.unhandled);
	}
	fz_catch(ctx)
	{
		fprintf(stderr, "%s\n", fz_caught_message(ctx));
		fz_report_error(ctx);
		failed = 1;
	}
	fz_drop_context(ctx);
	if (!failed)
		printf("JPEG XL %s tests passed (%d checks)\n", FZ_ENABLE_JXL ? "decoder" : "disabled-build", checks);
	return failed;
}
